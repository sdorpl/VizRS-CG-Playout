#!/usr/bin/env python3
"""docker-compose.portainer.yml: the one stack of s1 and s2 (Portainer, one Compose path).

Generated from docker-compose.yml + docker-compose.ampere.yml + docker-compose.live.yml
(what s1 ran as three files) by `docker compose config --no-interpolate`, so it never
drifts from them (docker-compose.s2-stack.yml did). Every setting is the same on both
servers; a Portainer stack sets only what has to differ (DOKUMENTACJA §4):

    STACK_PREFIX       names of the volumes and the network (s1 vizplay, s2 repo)
    ERSATZTV_CONFIG    ErsatzTV's config: a volume (default) or a host path (s2 /etc/ersatz)
    MEDIA_DIR          the media on the host (s1 /media, s2 /media/tv)
    MEDIA_MOUNT        where ErsatzTV and VizRS Live see them (s1 /media, s2 /media/tv)
    tokens, domains, VIZRS_INGEST (the server's channels)

The ingest service runs without the profile: both servers take live signals.

    python3 scripts/portainer-stack.py           # writes docker-compose.portainer.yml
    python3 scripts/portainer-stack.py --check   # exit 1 when it is not up to date (CI)

Needs docker compose and PyYAML (a tool of the repository, not of the sidecar).
"""

import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ["docker-compose.yml", "docker-compose.ampere.yml", "docker-compose.live.yml"]
OUT = ROOT / "docker-compose.portainer.yml"
PREFIX = "${STACK_PREFIX:-vizplay}"
CONFIG = "${ERSATZTV_CONFIG:-ersatztv-config}"
MEDIA = "${MEDIA_DIR:-seed-media}"

HEADER = """\
# s1 and s2: the whole stack in one file for Portainer (Repository → Compose path:
# docker-compose.portainer.yml, no Additional paths; a Portainer agent cannot build).
# GENERATED by scripts/portainer-stack.py from docker-compose.yml,
# docker-compose.ampere.yml and docker-compose.live.yml – change those and run it.
# The settings are the same on both servers; a stack sets only STACK_PREFIX,
# ERSATZTV_CONFIG, MEDIA_DIR, MEDIA_MOUNT, the tokens, the domains and
# VIZRS_INGEST (DOKUMENTACJA §4, „Stosy s1 i s2”).
"""


def merged() -> dict:
    args = ["docker", "compose"]
    for source in SOURCES:
        args += ["-f", source]
    # Without .env and the caller's variables: only the files' own defaults.
    env = {"PATH": "/usr/bin:/bin:/usr/local/bin", "HOME": str(Path.home())}
    text = subprocess.run(args + ["config", "--no-interpolate"], cwd=ROOT, env=env, check=True, capture_output=True, text=True).stdout
    return yaml.safe_load(text)


def volume(mount: dict):
    """A mount of the stack, with the server's places where they differ."""
    source, target = mount.get("source"), mount.get("target")
    ro = ":ro" if mount.get("read_only") else ""
    if source == "ersatztv-config":
        return f"{CONFIG}:{target}{ro}"
    if source == MEDIA:
        return f"{MEDIA}:${{MEDIA_MOUNT:-/media}}{ro}"
    return mount


def stack() -> dict:
    doc = merged()
    doc.pop("name", None)
    doc["networks"] = {"default": {"name": f"{PREFIX}_default"}}
    for key in doc.get("volumes", {}):
        doc["volumes"][key] = {"name": f"{PREFIX}_{key}"}
    for config in doc.get("configs", {}).values():
        config.pop("name", None)
    for name, service in doc["services"].items():
        service.pop("profiles", None)
        if "volumes" in service:
            service["volumes"] = [volume(m) if isinstance(m, dict) else m for m in service["volumes"]]
        if "build" in service:
            raise SystemExit(f"{name}: a build in the stack (a Portainer agent cannot build)")
    return doc


class Dumper(yaml.SafeDumper):
    pass


def text_block(dumper, value):
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


Dumper.add_representer(str, text_block)


def render() -> str:
    return HEADER + yaml.dump(stack(), Dumper=Dumper, sort_keys=False, width=1000, allow_unicode=True)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} is not up to date: python3 scripts/portainer-stack.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"{OUT.name} written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
